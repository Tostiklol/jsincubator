/*
* Напишите функцию truncate, которая принимает строку и максимальную длину.

* Если длина строки превышает указанное количество символов, функция должна обрезать строку до этой длины и добавлять в конец многоточие (...).
* В противном случае функция должна возвращать исходную строку.

* Пример работы функции:
* truncate("Вот, что мне действительно нравится в этом", 20) // Ожидаемый результат: "Вот, что мне действи..."
* truncate("Короткая строка", 20) // Ожидаемый результат: "Короткая строка"
*/

function truncate(str, maxLength) {
  // Если строка короче или равна maxLength
  if (str.length <= maxLength) {
    return str;
  }
  
  // Если исходная строка уже содержит многоточие где-то внутри
  // и оно попадает в первые maxLength символов
  const possibleResult = str.substring(0, maxLength);
  
  // Если обрезанная строка уже заканчивается на многоточие
  if (possibleResult.endsWith("...")) {
    return possibleResult;
  }
  
  // Если исходная строка содержит многоточие, но не в конце обрезанной версии
  // Или если многоточия нет вообще
  // Обрезаем до maxLength - 3 и добавляем многоточие
  return str.substring(0, maxLength - 3) + "...";
}